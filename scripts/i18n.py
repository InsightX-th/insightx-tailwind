#!/usr/bin/env python3
"""Regenerate translations: JS strings -> src/I18n.php -> .pot -> merge into .po -> .mo.

Run from the plugin root:  python3 scripts/i18n.py
Then translate any new empty msgstr in languages/*.po and run it again.
Needs gettext (xgettext, msgmerge, msgfmt).
"""
import glob
import re
import subprocess

DOMAIN = 'insightx-tailwind'

strings = set()
for path in glob.glob('app/src/**/*.ts', recursive=True) + glob.glob('app/src/**/*.vue', recursive=True):
    if path.endswith('.test.ts'):
        continue
    src = open(path, encoding='utf-8').read()
    for m in re.finditer(r"""__\(\s*(?:'((?:[^'\\]|\\.)*)'|"([^"]*)")""", src):
        strings.add(m.group(1).replace("\\'", "'") if m.group(1) is not None else m.group(2))

esc = lambda s: s.replace('\\', '\\\\').replace("'", "\\'")
body = '\n'.join(f"            '{esc(s)}' => __('{esc(s)}', '{DOMAIN}')," for s in sorted(strings))
open('src/I18n.php', 'w', encoding='utf-8').write(f"""<?php

declare(strict_types=1);

namespace InsightX\\Tailwind;

/**
 * UI strings for the JS bundles. Keys are the English source strings used
 * with `__()` in app/src (see app/src/config.ts), so one .po file covers
 * PHP and JS. Generated by scripts/i18n.py — don't edit by hand.
 */
final class I18n
{{
    /** @return array<string, string> */
    public static function strings(): array
    {{
        // translators: %s placeholders are filled in order by the JS UI.
        return [
{body}
        ];
    }}
}}
""")

php = ['insightx-tailwind.php'] + sorted(glob.glob('src/**/*.php', recursive=True))
subprocess.run(['xgettext', '--language=PHP', '--from-code=UTF-8', '--add-comments=translators',
                '--keyword=__', '--keyword=esc_html__', '--keyword=esc_html_e', '--keyword=esc_attr__',
                '--package-name=InsightX Tailwind', f'-o', f'languages/{DOMAIN}.pot', *php], check=True)

for po in glob.glob(f'languages/{DOMAIN}-*.po'):
    subprocess.run(['msgmerge', '--quiet', '--update', '--backup=none', '--no-fuzzy-matching', po, f'languages/{DOMAIN}.pot'], check=True)
    subprocess.run(['msgfmt', '--check', '--statistics', '-o', po[:-3] + '.mo', po], check=True)

print(f'{len(strings)} JS strings, {len(php)} PHP files')
